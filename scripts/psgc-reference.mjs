#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { basename, resolve } from "node:path";

const [command, manifestPathInput = 'data/psgc/2026-q2.manifest.json'] = process.argv.slice(2);
if (!['validate', 'sql'].includes(command)) {
  console.error('Usage: node scripts/psgc-reference.mjs <validate|sql> [manifest.json]');
  process.exit(2);
}

const manifestPath = resolve(manifestPathInput);
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const csvPath = resolve(manifestPath, '..', manifest.dataFile);
const csv = readFileSync(csvPath, 'utf8');

function parseCsv(source) {
  const rows = [];
  let row = [];
  let value = '';
  let quoted = false;
  for (let index = 0; index < source.length; index += 1) {
    const char = source[index];
    if (quoted) {
      if (char === '"' && source[index + 1] === '"') {
        value += '"';
        index += 1;
      } else if (char === '"') quoted = false;
      else value += char;
    } else if (char === '"') quoted = true;
    else if (char === ',') {
      row.push(value);
      value = '';
    } else if (char === '\n') {
      row.push(value.replace(/\r$/, ''));
      rows.push(row);
      row = [];
      value = '';
    } else value += char;
  }
  if (value || row.length) {
    row.push(value.replace(/\r$/, ''));
    rows.push(row);
  }
  if (quoted) throw new Error('Unterminated quoted CSV value');
  return rows;
}

const parsed = parseCsv(csv);
const expectedHeader = ['code', 'name', 'type', 'parent_code', 'city_class'];
if (JSON.stringify(parsed[0]) !== JSON.stringify(expectedHeader)) {
  throw new Error(`Unexpected CSV header in ${basename(csvPath)}`);
}

const rows = parsed.slice(1).filter((row) => row.some(Boolean)).map((row, index) => {
  if (row.length !== expectedHeader.length) throw new Error(`Invalid column count on CSV row ${index + 2}`);
  const [code, name, type, parentCode, cityClass] = row;
  if (!/^\d{10}$/.test(code) || !name.trim()) throw new Error(`Invalid identity on CSV row ${index + 2}`);
  if (!['region', 'province', 'city', 'municipality', 'submunicipality', 'barangay'].includes(type)) {
    throw new Error(`Invalid type on CSV row ${index + 2}`);
  }
  if ((type === 'region') !== !parentCode) throw new Error(`Invalid root relationship for ${code}`);
  if ((type === 'city') !== Boolean(cityClass)) throw new Error(`Invalid city class for ${code}`);
  if (cityClass && !['CC', 'HUC', 'ICC'].includes(cityClass)) throw new Error(`Invalid city class for ${code}`);
  return { cityClass: cityClass || null, code, name: name.trim(), parentCode: parentCode || null, type };
});

const byCode = new Map();
for (const row of rows) {
  if (byCode.has(row.code)) throw new Error(`Duplicate PSGC code ${row.code}`);
  byCode.set(row.code, row);
}

for (const row of rows) {
  if (row.type === 'region') continue;
  const parent = byCode.get(row.parentCode);
  if (!parent) throw new Error(`Missing parent ${row.parentCode} for ${row.code}`);
  const valid =
    (row.type === 'province' && parent.type === 'region') ||
    (row.type === 'city' && ['HUC', 'ICC'].includes(row.cityClass) && parent.type === 'region') ||
    (row.type === 'city' && row.cityClass === 'CC' && parent.type === 'province') ||
    (row.type === 'municipality' && ['region', 'province'].includes(parent.type)) ||
    (row.type === 'submunicipality' && parent.type === 'city') ||
    (row.type === 'barangay' && ['city', 'municipality', 'submunicipality'].includes(parent.type));
  if (!valid) throw new Error(`Invalid ${row.type} parent for ${row.code}`);
}

const counts = rows.reduce((value, row) => {
  value[row.type] = (value[row.type] ?? 0) + 1;
  return value;
}, {});
const actual = {
  barangays: counts.barangay ?? 0,
  localities: (counts.city ?? 0) + (counts.municipality ?? 0),
  provinces: counts.province ?? 0,
  regions: counts.region ?? 0,
  submunicipalities: counts.submunicipality ?? 0,
};
if (JSON.stringify(actual) !== JSON.stringify(manifest.counts)) {
  throw new Error(`Count mismatch: ${JSON.stringify(actual)}`);
}

const normalizedSha256 = createHash('sha256').update(csv).digest('hex');
if (normalizedSha256 !== manifest.normalizedSha256) {
  throw new Error(`Normalized CSV digest mismatch: ${normalizedSha256}`);
}

if (command === 'validate') {
  console.log(JSON.stringify({ release: manifest.release, rows: rows.length, counts: actual, normalizedSha256 }));
  process.exit(0);
}

const quote = (value) => value === null ? 'null' : `'${String(value).replaceAll("'", "''")}'`;
const statements = [
  '-- Generated by scripts/psgc-reference.mjs. Do not hand-edit.',
  `-- Official source SHA-256: ${manifest.sourceSha256}`,
  'begin;',
  `insert into private.psgc_releases (release_key, source_title, source_url, source_sha256, effective_on, expected_region_count, expected_province_count, expected_locality_count, expected_submunicipality_count, expected_barangay_count) values (${quote(manifest.release)}, ${quote(manifest.sourceTitle)}, ${quote(manifest.sourceUrl)}, ${quote(manifest.sourceSha256)}, ${quote(manifest.effectiveOn)}, ${actual.regions}, ${actual.provinces}, ${actual.localities}, ${actual.submunicipalities}, ${actual.barangays});`,
];
for (let index = 0; index < rows.length; index += 500) {
  const values = rows.slice(index, index + 500).map((row) =>
    `(${quote(manifest.release)},${quote(row.code)},${quote(row.name)},${quote(row.type)}::private.psgc_area_type,${quote(row.parentCode)},${quote(row.cityClass)},${quote(manifest.effectiveOn)})`
  );
  statements.push('insert into private.psgc_areas (release_key, code, name, area_type, parent_code, city_class, valid_from) values\n' + values.join(',\n') + ';');
}
statements.push('set local role service_role;');
statements.push(`select private.activate_psgc_release(${quote(manifest.release)});`);
// Hosted migrations run through a temporary login role that assumes `postgres`.
// RESET ROLE would return to that unprivileged login before the CLI records the
// migration, so restore the migration role explicitly inside this transaction.
statements.push('-- Restore the hosted migration role before the CLI records history.');
statements.push('set local role postgres;');
statements.push('commit;');
process.stdout.write(statements.join('\n\n') + '\n');
